      nq = 2*nq
    end do
    if( iter > MaxIter ) stop 'cheb_coefficients: quadratures not converged'
    theta = pi/(order + 2)
    !
    if( kernel == 'jackson' ) then
      do m=0,order
        g = ((order + 2 - m)*cos(m*theta) + sin(m*theta)/tan(theta))/(order + 2)
        coeff(m) = coeff(m)*g
      enddo
    endif
    !
    if(activate_) call cheb_set(a, b, coeff)
    !
  end subroutine coefficients_c









  subroutine set_d(a, b, coeff, info)
    !Set the internal memory for the Chebyshev expansion, real coefficients.
    !
    !Stores the scale :f:var:`a`, the shift :f:var:`b` and, if present, the coefficients, see
    !:f:func:`cheb_set`. With no coefficients, only the scale and the shift are prepared and the
    !old expansion is invalidated.
    !
    !Real version: the coefficients are also kept as complex numbers.
    real(8), intent(in)            :: a        !Scale of the map :math:`\tilde{A} = (A - b)/a`, must be positive
    real(8), intent(in)            :: b        !Shift of the map :math:`\tilde{A} = (A - b)/a`
    real(8), optional, intent(in)  :: coeff(0:)!Chebyshev coefficients :math:`c_0, \dots, c_M` to store. If absent, any stored
    ! coefficients are discarded
    integer, optional, intent(out) :: info     !Exit code: :code:`0` on success, :code:`1` if :f:var:`a` is not positive or
    ! :f:var:`coeff` is empty (the stored state is then unchanged). If absent, a
    ! failure stops the program
    integer                        :: status !error code
    !
    status = 1
    !
    !Use block (yeah I learned some new Fortran feature... ) to implement teh ckecks in a compact way
    setup: block
      if(a <= 0d0) exit setup
      if(present(coeff)) then
        if(size(coeff) == 0) exit setup
      end if
      if(allocated(cheb_coeff)) deallocate (cheb_coeff)
      if(allocated(cheb_zcoeff)) deallocate (cheb_zcoeff)
      if(present(coeff)) then
        allocate (cheb_coeff(0:size(coeff) - 1), cheb_zcoeff(0:size(coeff) - 1))
        cheb_coeff = coeff
        cheb_zcoeff = cmplx(coeff, 0d0, 8)
      end if
      cheb_a = a
      cheb_b = b
      complex_coeff = .false.
      scale_ready = .true.
      status = 0
    end block setup
    if(present(info)) info = status
    if(status /= 0 .and. .not. present(info)) stop 'cheb_set: invalid inputs'
  end subroutine set_d

  subroutine set_c(a, b, coeff, info)
    !Set the internal memory for the Chebyshev expansion, complex coefficients.
    !
    !Same as the real version, see :f:func:`cheb_set`, but with complex coefficients. The real parts
    !are also stored, for the real recurrence, which can be used only if all the imaginary parts vanish.
    !
    !:callto: set_d
    real(8), intent(in)            :: a        !Scale of the map :math:`\tilde{A} = (A - b)/a`, must be positive
    real(8), intent(in)            :: b        !Shift of the map :math:`\tilde{A} = (A - b)/a`
    complex(8), intent(in)         :: coeff(0:)!Chebyshev coefficients :math:`c_0, \dots, c_M` to store
    integer, optional, intent(out) :: info     !Exit code: :code:`0` on success, :code:`1` if :f:var:`a` is not positive or
    ! :f:var:`coeff` is empty (the stored state is then unchanged). If absent, a
    ! failure stops the program
    integer                        :: status
    status = 1
    setup: block
      if(a <= 0d0 .or. size(coeff) == 0) exit setup
      call set_d(a, b)
      allocate (cheb_coeff(0:size(coeff) - 1), cheb_zcoeff(0:size(coeff) - 1))
      cheb_coeff = real(coeff, 8)
      cheb_zcoeff = coeff
      complex_coeff = maxval(abs(aimag(coeff))) > 0d0
      status = 0
    end block setup
    if(present(info)) info = status
    if(status /= 0 .and. .not. present(info)) stop 'cheb_set: invalid inputs'
  end subroutine set_c











  !DBLE:
  subroutine recurrence_d(MatVec, Vseed, values, status, nop, rows, U, moments)
    !The WORKHORSE Chebyshev recurrence method, real version.
    !
    !This is the core of the algorithm: it approximates :math:`f(A) v`, projected as requested,
    !knowing only the seed vector :math:`v \in \mathbb{R}^N` and the action of :math:`A` on vectors
    !of :math:`\mathbb{R}^N` (:code:`MatVec`). It runs the recurrence
    !
    !.. math::
    !
    !   T_0 v = v, \qquad T_1 v = \tilde{A} v, \qquad T_{m+1} v = 2 \tilde{A}\, T_m v - T_{m-1} v,
    !
    !with :math:`\tilde{A} = (A - b)/a` (scale and shift stored in the module memory) and, at each
    !step, projects :math:`T_m v` on the requested rows or vectors.
    !
    !The projection is selected by one of the optional arguments :f:var:`rows` and :f:var:`u`: one
    !of them must be present. If both are, :f:var:`rows` is used and :f:var:`u` is ignored.
    !
    !The result is the sum of the projections weighted by the stored coefficients, returned in
    !:f:var:`values`. If :f:var:`moments` is present, the unweighted projections are returned in it
    !instead and :f:var:`values` is zero: the coefficients need not be set in this case, but the scale
    !and the shift must.
    !
    !Used by all the implementations of :f:func:`cheb_projection` and :f:func:`cheb_moments`.
    !
    interface
      subroutine MatVec(Nloc, vin, vout)   !Matrix-vector product subroutine, :code:`vout = A*vin`, on vectors of length :code:`Nloc`
        integer :: Nloc
        real(8) :: vin(Nloc), vout(Nloc)
      end subroutine MatVec
    end interface
    real(8), intent(in)            :: Vseed(:)    !Seed vector :math:`v`, of size :math:`N`
    real(8), intent(out)           :: values(:)   !Output :math:`\sum_m c_m P T_m(\tilde{A}) v`, one value for each row or column
    ! of :f:var:`u` requested. Zero if :f:var:`moments` is present or on failure
    integer, intent(out)           :: status      !Exit code: :code:`0` success; :code:`1` invalid input (inconsistent sizes,
    ! rows out
    ! of range, neither :f:var:`rows` nor :f:var:`u`, empty seed or
    ! :f:var:`moments`,
    ! complex stored coefficients); :code:`3` scale and shift not set, or
    ! coefficients
    ! not set when :f:var:`moments` is absent. Code :code:`2` is internal
    integer, intent(out)           :: nop         !Number of calls to :code:`MatVec`
    integer, optional, intent(in)  :: rows(:)     !Indices, between 1 and :math:`N`, of the components of :math:`T_m v` to
    ! extract;
    ! the size must be that of :f:var:`values`
    real(8), optional, intent(in)  :: U(:, :)     !Matrix of shape :math:`N \times K` whose columns :math:`u_k` are contracted
    ! with
    ! :math:`T_m v`, :math:`K` being the size of :f:var:`values`
    real(8), optional, intent(out) :: moments(:, 0:) !If present, receives the moments :code:`moments(k,m)`, the projection
    ! :math:`k`
    ! of :math:`T_m v`, up to :math:`M` = :code:`size(moments,2) - 1`
    real(8)                        :: t0(size(Vseed)), t1(size(Vseed)), t2(size(Vseed)), projected(size(values))
    integer                        :: n, m, k, order
    !
    N      = size(Vseed)
    status = 1
    nop    = 0
    values = 0d0
    if(present(moments)) moments = 0d0
    !
    !Use a block to implement checks and early exit
    evaluation: block
      if(.not. scale_ready) then
        status = 3
        exit evaluation
      end if
      if(n == 0) exit evaluation
      !
      if(present(rows)) then
        if(size(rows) /= size(values)) exit evaluation
        if(any(rows < 1) .or. any(rows > n)) exit evaluation
      else if(present(U)) then
        if(size(U, 1) /= n .or. size(U, 2) /= size(values)) exit evaluation
      else
        exit evaluation
      end if
      !
      if(present(moments)) then
        if(size(moments, 1) /= size(values) .or. size(moments, 2) == 0) exit evaluation
        order = size(moments,2)-1
      else
        if(.not. allocated(cheb_coeff)) then
          status = 3
          exit evaluation
        end if
        if(complex_coeff) exit evaluation
        order = size(cheb_coeff) - 1
      end if
      !
      !
      !Now, the actual recurrence
      status = 2
      t0     = Vseed
      do m=0,order
        !
        if(m > 0) then
          call MatVec(n, t0, t2)
          nop = nop + 1
          t2  = (t2 - cheb_b*t0)/cheb_a
          if( m > 1 )t2 = 2d0*t2 - t1
          t1 = t0
          t0 = t2
        end if
        !
        if(present(rows)) then
          projected = t0(rows)
        else
          do k = 1, size(values)
            projected(k) = dot_product(U(:, k), t0)
          end do
        end if
        !
        if(present(moments)) then
          moments(:, m) = projected
        else
          values = values + cheb_coeff(m)*projected
        end if
      end do
      !
      status = 0
    end block evaluation
    !
    !
    if(status /= 0) then
      values = 0d0
      if(present(moments)) moments = 0d0
    end if
  end subroutine recurrence_d

