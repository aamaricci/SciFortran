module SF_CHEBYCHEV
!:synopsis: Chebyshev expansion of functions of a linear operator, using only matrix-vector products
!Approximation of :math:`f(A)\,v`, the action of a function of a linear operator :math:`A` on a seed
!vector :math:`v`, by a truncated Chebyshev series. The operator is never needed explicitly: only its
!action on a vector is used, through a user-supplied matrix-vector product (:code:`MatVec`).
!
!The operator is first mapped onto :math:`[-1, 1]`,
!
!.. math::
!
!   \tilde{A} = \frac{A - b}{a},
!
!where :math:`a > 0` is the *scale* and :math:`b` the *shift*: the spectrum of :math:`A` must lie in
!:math:`[b - a,\, b + a]`. The function is then expanded as
!
!.. math::
!
!   f(A) \simeq \sum_{m=0}^{M} c_m\, T_m(\tilde{A}),
!
!where :math:`T_m` is the Chebyshev polynomial of the first kind and degree :math:`m`. Applied to the
!seed vector, the polynomials are generated by the recurrence
!
!.. math::
!
!   T_0 v = v, \qquad T_1 v = \tilde{A} v, \qquad T_{m+1} v = 2 \tilde{A}\, T_m v - T_{m-1} v,
!
!so that only :math:`M` products of :math:`A` with a vector are needed.
!
!The module provides four generic interfaces:
!
!* :f:func:`cheb_coefficients`: compute the coefficients :math:`c_m` of a given function, optionally
!  damped by the Jackson kernel;
!* :f:func:`cheb_set`: store the scale, the shift and the coefficients in the module memory;
!* :f:func:`cheb_projection`: evaluate the expansion, projected on selected components or vectors;
!* :f:func:`cheb_moments`: compute the individual terms :math:`T_m(\tilde{A})\,v` of the expansion,
!  projected in the same way, which do not depend on the coefficients.
!
!Every interface exists for ``real(8)`` and for ``complex(8)`` data.
!
!.. note::
!
!   The scale, the shift and the coefficients are kept in module-level variables shared by all the
!   calls: the module is not thread safe. Invalid input is reported through the optional argument
!   :code:`info` of :f:func:`cheb_set`, :f:func:`cheb_projection` and :f:func:`cheb_moments`; if it is
!   absent the program stops. :f:func:`cheb_coefficients` always stops on invalid input.
!
!Example, with the spectrum of :math:`A` in :math:`[-4, 4]` (:code:`gauss` is a real function of one
!real variable and :code:`MatVec` the matrix-vector product of :math:`A`):
!
!.. code-block:: fortran
!
!   real(8) :: coeff(0:99), w(3)
!   call cheb_coefficients(gauss, 4d0, 0d0, coeff, kind="jackson")
!   call cheb_projection(MatVec, vseed, [1, 2, 3], w)
!
  USE SF_CONSTANTS, only: pi, zero
  USE SF_IOTOOLS, only: to_lower, str
  implicit none
  private

  interface cheb_coefficients
    !Chebyshev coefficients of a function, real or complex valued.
    !
    !Computes the coefficients :math:`c_m`, :math:`m = 0, \dots, M`, of the expansion
    !
    !.. math::
    !
    !   f(x) \simeq \sum_{m=0}^{M} c_m\, T_m\!\left(\frac{x - b}{a}\right),
    !   \qquad x \in [b - a,\, b + a],
    !
    !where :math:`M + 1` is the size of the output array :f:var:`coeff`.
    !
    !The coefficients are obtained by Chebyshev-Gauss quadrature with :math:`n_q` nodes,
    !
    !.. math::
    !
    !   c_m = \frac{2 - \delta_{m0}}{n_q} \sum_{j=1}^{n_q} f(a \cos\theta_j + b)\, \cos(m \theta_j),
    !   \qquad \theta_j = \frac{\pi (j - 1/2)}{n_q}.
    !
    !Starting from :math:`n_q = \max(64,\, 2(M + 1))`, the number of nodes is doubled until two
    !successive sets of coefficients differ by less than :f:var:`tol`, relative to
    !:math:`\max(1, \max_m |c_m|)`; the iteration is aborted after 128 doublings.
    !
    !If :f:var:`kind` selects the Jackson kernel, the coefficients are damped to reduce the Gibbs
    !oscillations of the truncated series, :math:`c_m \to g_m c_m`, with
    !
    !.. math::
    !
    !   g_m = \frac{(M + 2 - m) \cos\frac{\pi m}{M + 2}
    !   + \sin\frac{\pi m}{M + 2} \cot\frac{\pi}{M + 2}}{M + 2}.
    !
    !Unless :f:var:`activate` is false, the scale, the shift and the coefficients are also stored in
    !the module memory (see :f:func:`cheb_set`), ready for :f:func:`cheb_projection`.
    !
    !The function :f:var:`fun` takes one ``real(8)`` argument; it returns a ``real(8)`` value for real
    !coefficients and a ``complex(8)`` value for complex coefficients.
    !
    !The program stops if :f:var:`kind` is unknown, if :f:var:`tol` is not positive, if :f:var:`a` is
    !not positive, if :f:var:`coeff` is empty, or if the quadrature cannot be converged.
    module procedure :: coefficients_d
    module procedure :: coefficients_c
  end interface cheb_coefficients

  interface cheb_set
    !Store the scale, the shift and, optionally, the coefficients of the expansion in the module memory.
    !
    !The scale :math:`a`, the shift :math:`b` and the coefficients :math:`c_m` of the expansion
    !
    !.. math::
    !
    !   f(A) \simeq \sum_{m=0}^{M} c_m\, T_m\!\left(\frac{A - b}{a}\right)
    !
    !are kept in the module memory, from which :f:func:`cheb_projection` and :f:func:`cheb_moments`
    !read them. :f:func:`cheb_coefficients` does it automatically; call :f:func:`cheb_set` directly to
    !use coefficients computed elsewhere, or to change the scale and the shift only.
    !
    !.. code-block:: fortran
    !
    !   call cheb_set(a, b [, coeff, info])
    !
    !* With coefficients, they replace the stored ones. Complex coefficients are flagged as complex if
    !  at least one of them has a non-zero imaginary part: the real version of
    !  :f:func:`cheb_projection` then refuses to run.
    !* Without coefficients (real version only), just the scale and the shift are set and any stored
    !  expansion is discarded. This is enough for :f:func:`cheb_moments`.
    !
    !Invalid input (non-positive scale, or empty coefficients) leaves the module memory unchanged:
    !:f:var:`info` is set to :code:`1` or, if it is absent, the program stops.
    module procedure :: set_d
    module procedure :: set_c
  end interface cheb_set

  interface cheb_projection
    !Evaluate :math:`f(A)\,v` with the stored Chebyshev expansion, projected on selected components or vectors.
    !
    !Using the scale :math:`a`, the shift :math:`b` and the coefficients :math:`c_m` stored in the module
    !memory (see :f:func:`cheb_coefficients` and :f:func:`cheb_set`), it computes
    !
    !.. math::
    !
    !   w = P f(A) v \simeq \sum_{m=0}^{M} c_m\, P\, T_m(\tilde{A})\, v,
    !   \qquad \tilde{A} = \frac{A - b}{a},
    !
    !for the seed vector :math:`v` (:f:var:`vseed`), with :math:`M` products of :math:`A` with a
    !vector, supplied by the callback :code:`MatVec`. The projection :math:`P` is selected by the
    !third argument:
    !
    !* an integer array :f:var:`rows`: :math:`w_k = [f(A)v]_{r_k}`, the components :math:`r_k` of the result;
    !* a matrix :f:var:`u`: :math:`w_k = u_k^\dagger f(A) v`, the scalar product with the column
    !  :math:`u_k` of :math:`U` (conjugated for complex vectors).
    !
    !.. code-block:: fortran
    !
    !   call cheb_projection(MatVec, Vseed, rows, values [, info, NumOp])
    !   call cheb_projection(MatVec, Vseed, U,    values [, info, NumOp])
    !
    !With the real version the stored coefficients must be real.
    !
    !On exit :f:var:`info` is :code:`0` on success, :code:`1` for invalid input (inconsistent sizes,
    !rows out of range, empty seed, or complex coefficients with real vectors) and :code:`3` if the
    !scale or the coefficients have not been set. If :f:var:`info` is absent, a failure stops the program.
    module procedure :: projection_rows_d
    module procedure :: projection_rows_c
    module procedure :: projection_vectors_c
    module procedure :: projection_vectors_d
  end interface cheb_projection

  interface cheb_moments
    !Chebyshev moments of the seed vector, projected on selected components or vectors.
    !
    !Computes the moments
    !
    !.. math::
    !
    !   \mu_{k,m} = [P\, T_m(\tilde{A})\, v]_k, \qquad \tilde{A} = \frac{A - b}{a},
    !   \qquad m = 0, \dots, M,
    !
    !for the seed vector :math:`v` (:f:var:`vseed`), where :math:`M + 1` is the number of columns of
    !:f:var:`moments`. The projection :math:`P` is selected as in :f:func:`cheb_projection`:
    !
    !* an integer array :f:var:`rows`: :math:`\mu_{k,m} = [T_m(\tilde{A}) v]_{r_k}`;
    !* a matrix :f:var:`u`: :math:`\mu_{k,m} = u_k^\dagger T_m(\tilde{A}) v` (conjugated for complex vectors).
    !
    !.. code-block:: fortran
    !
    !   call cheb_moments(MatVec, Vseed, rows, moments [, info, NumOp])
    !   call cheb_moments(MatVec, Vseed, U,    moments [, info, NumOp])
    !
    !The moments do not depend on the coefficients: they are computed once and can be combined later
    !with the coefficients of any function, :math:`P f(A) v \simeq \sum_m c_m \mu_{\cdot,m}`. The scale
    !and the shift, however, must have been set (:f:func:`cheb_set`, even without coefficients).
    !
    !On exit :f:var:`info` is :code:`0` on success, :code:`1` for invalid input (inconsistent sizes,
    !rows out of range, empty seed) and :code:`3` if the scale and the shift have not been set. If
    !:f:var:`info` is absent, a failure stops the program.
    module procedure :: moments_rows_d
    module procedure :: moments_rows_c
    module procedure :: moments_vectors_d
    module procedure :: moments_vectors_c
  end interface cheb_moments

  public :: cheb_coefficients
  public :: cheb_set
  public :: cheb_projection
  public :: cheb_moments

  !Variables.
  !shift and rescale global Factors:
  real(8), save                 :: cheb_a = 1d0             !Scale :math:`a` of the map :math:`\tilde{A} = (A - b)/a`
  real(8), save                 :: cheb_b = 0d0             !Shift :math:`b` of the map :math:`\tilde{A} = (A - b)/a`
  logical, save                 :: scale_ready = .false.    !True once the scale and the shift have been set
  logical, save                 :: complex_coeff = .false.  !True if the stored coefficients have a non-zero imaginary part
  real(8), allocatable, save    :: cheb_coeff(:)            !Stored coefficients :math:`c_m`, :math:`m = 0, \dots, M` (real part
  ! if complex)
  complex(8), allocatable, save :: cheb_zcoeff(:)           !Stored coefficients :math:`c_m`, :math:`m = 0, \dots, M`, as complex
  ! numbers

contains





  subroutine coefficients_d(fun, a, b, coeff, kind, tol, activate)
    !Chebyshev coefficients of a real function, see :f:func:`cheb_coefficients`.
    !
    !Real version: the function and the coefficients are ``real(8)``.
    !
    !
    !:callto: cheb_set
    interface
      function fun(x) !Real/complex function of one real variable, sampled on :math:`[b - a,\, b + a]`
        real(8), intent(in) :: x
        real(8)             :: fun
      end function fun
    end interface
    logical, optional, intent(in) :: activate  !If :code:`.true.`, :f:var:`a`, :f:var:`b` and :f:var:`coeff` are stored in the
    ! module memory with :f:func:`cheb_set`. Default :code:`.true.`
    logical                       :: activate_
    integer, parameter            :: MaxIter = 128
    real(8), intent(in)           :: a         !Scale: half-width of the interval :math:`[b - a,\, b + a]`, must be positive
    real(8), intent(in)           :: b         !Shift: center of the interval :math:`[b - a,\, b + a]`
    real(8), intent(out)          :: coeff(0:) !Chebyshev coefficients :math:`c_0, \dots, c_M`; the size fixes the order
    ! :math:`M` = :code:`size(coeff) - 1`
    character(len=*), optional    :: kind      !Damping kernel, case insensitive: :code:`"jackson"` (or :code:`"j"`) or
    ! :code:`"none"` (or :code:`"n"`). Default :code:`"none"`
    real(8), optional, intent(in) :: tol       !Relative tolerance of the quadrature, must be positive. Default :code:`1d-12`
    integer                       :: m, order, j, nq, iter
    real(8)                       :: theta, eps, g, value
    real(8)                       :: previous(0:size(coeff) - 1)
    character(len=16)             :: kernel
    !
    activate_ = .true.; if(present(activate)) activate_ = activate
    kernel    = 'none'; if(present(kind)) kernel = kind
    eps       = 1d-12 ; if(present(tol)) eps = tol
    !
    !Checks:
    select case (to_lower(str(kernel)))
     case ('jackson', 'j'); kernel = 'jackson'
     case ('none', 'n'); kernel = 'none'
     case default; stop 'cheb_coefficients: unknown kernel'
    end select
    !
    if(eps <= 0d0) stop 'cheb_coefficients: invalid tolerance'
    if(a <= 0d0 .OR. size(coeff) == 0) stop 'cheb_coefficients: invalid inputs a,b,coeff'
    !
    order = size(coeff) - 1
    theta = pi/(order + 2)
    nq    = max(64, 2*size(coeff))
    previous = 0d0
    !
    do iter=1,MaxIter
      coeff = 0d0
      do j=1,nq
        theta = pi*(j - 0.5d0)/nq
        value = fun(a*cos(theta) + b) !Any check on value?
        do m=0,order
          coeff(m) = coeff(m) + value*cos(m*theta)
        enddo
      enddo
      !
      coeff    = 2d0*coeff/nq
      coeff(0) = coeff(0)/2d0
      if(iter > 1)then
        if( maxval(abs(coeff - previous)) <= eps*max(1d0, maxval(abs(coeff))) ) exit
      end if
      previous = coeff
      if( nq > ishft(huge(nq), -1) ) stop 'cheb_coefficients: quadrature size overflow'
      nq = 2*nq
    end do
    if(iter > MaxIter) stop 'cheb_coefficients: quadratures not converged'
    theta = pi/(order + 2)
    !
    if(kernel == 'jackson')then
      do m=0,order
        g = ((order + 2 - m)*cos(m*theta) + sin(m*theta)/tan(theta))/(order + 2)
        coeff(m) = coeff(m)*g
      enddo
    endif
    !
    if(activate_) call cheb_set(a, b, coeff)
    !
  end subroutine coefficients_d

  subroutine coefficients_c(fun, a, b, coeff, kind, tol, activate)
    !Chebyshev coefficients of a complex function, see :f:func:`cheb_coefficients`.
    !
    !Complex version: the function and the coefficients are ``complex(8)``.
    !
    !:callto: cheb_set
    interface
      function fun(x)              !Real/complex function of one real variable, sampled on :math:`[b - a,\, b + a]`
        real(8), intent(in)         :: x
        complex(8)                  :: fun
      end function fun
    end interface
    logical, optional, intent(in) :: activate  !If :code:`.true.`, :f:var:`a`, :f:var:`b` and :f:var:`coeff` are stored in the
